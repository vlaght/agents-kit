#!/usr/bin/env python3
"""Generate vendor-specific subagent files from portable role definitions.

Source of truth: .agents/roles/<name>.md
  ---
  name: reviewer
  description: One line telling the orchestrator when to use this role.
  capabilities: [read, shell]      # any of: read, edit, shell, web
  ---
  Markdown body = the role's system prompt.

Targets:
  claude   -> .claude/agents/<name>.md
  opencode -> .opencode/agents/<name>.md
  copilot  -> .github/agents/<name>.agent.md

Usage:
  python3 scripts/sync_agents.py                  # write all targets
  python3 scripts/sync_agents.py --target claude  # only some targets (repeatable)
  python3 scripts/sync_agents.py --check          # exit 1 if generated files are stale

Standard library only, so it runs anywhere Python 3.8+ is installed.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ROLES_DIR = ROOT / ".agents" / "roles"
CAPABILITIES = {"read", "edit", "shell", "web"}
HEADER = "Generated by scripts/sync_agents.py from .agents/roles/{name}.md. Do not edit; edit the role and re-run."


class RoleError(ValueError):
    pass


def parse_role(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.S)
    if not m:
        raise RoleError(f"{path}: missing frontmatter")
    meta: dict = {}
    for line in m.group(1).splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        key, sep, value = line.partition(":")
        if not sep:
            raise RoleError(f"{path}: bad frontmatter line: {line!r}")
        value = value.split(" #", 1)[0].strip()
        if value.startswith("[") and value.endswith("]"):
            meta[key.strip()] = [v.strip() for v in value[1:-1].split(",") if v.strip()]
        else:
            meta[key.strip()] = value
    for field in ("name", "description", "capabilities"):
        if field not in meta:
            raise RoleError(f"{path}: missing '{field}'")
    if meta["name"] != path.stem:
        raise RoleError(f"{path}: name '{meta['name']}' must match file name")
    unknown = set(meta["capabilities"]) - CAPABILITIES
    if unknown:
        raise RoleError(f"{path}: unknown capabilities {sorted(unknown)}")
    meta["capabilities"] = set(meta["capabilities"])
    meta["body"] = m.group(2).strip() + "\n"
    return meta


def yaml_str(value: str) -> str:
    # JSON strings are valid YAML scalars and handle quotes/colons safely.
    return json.dumps(value, ensure_ascii=False)


# --- Claude Code -----------------------------------------------------------
CLAUDE_TOOLS = {
    "read": ["Read", "Glob", "Grep"],
    "edit": ["Write", "Edit"],
    "shell": ["Bash"],
    "web": ["WebFetch", "WebSearch"],
}


def render_claude(role: dict) -> tuple[str, str]:
    tools = [t for cap in ("read", "edit", "shell", "web") if cap in role["capabilities"] for t in CLAUDE_TOOLS[cap]]
    out = (
        "---\n"
        f"name: {role['name']}\n"
        f"description: {yaml_str(role['description'])}\n"
        f"tools: {', '.join(tools)}\n"
        "---\n"
        f"<!-- {HEADER.format(name=role['name'])} -->\n\n"
        f"{role['body']}"
    )
    return f".claude/agents/{role['name']}.md", out


# --- OpenCode (v2 permissions list; last matching rule wins) ----------------
def render_opencode(role: dict) -> tuple[str, str]:
    caps = role["capabilities"]
    rules = []
    for cap, action in (("edit", "edit"), ("shell", "shell")):
        effect = "allow" if cap in caps else "deny"
        rules.append(f"  - action: {action}\n    resource: \"*\"\n    effect: {effect}\n")
    out = (
        "---\n"
        f"description: {yaml_str(role['description'])}\n"
        "mode: subagent\n"
        "permissions:\n"
        f"{''.join(rules)}"
        "---\n"
        f"<!-- {HEADER.format(name=role['name'])} -->\n\n"
        f"{role['body']}"
    )
    return f".opencode/agents/{role['name']}.md", out


# --- GitHub Copilot custom agents --------------------------------------------
COPILOT_TOOLS = {
    "read": ["read", "search"],
    "edit": ["edit"],
    "shell": ["execute"],
    "web": ["web"],
}


def render_copilot(role: dict) -> tuple[str, str]:
    tools = [t for cap in ("read", "edit", "shell", "web") if cap in role["capabilities"] for t in COPILOT_TOOLS[cap]]
    out = (
        "---\n"
        f"name: {role['name']}\n"
        f"description: {yaml_str(role['description'])}\n"
        f"tools: {json.dumps(tools)}\n"
        "---\n"
        f"<!-- {HEADER.format(name=role['name'])} -->\n\n"
        f"{role['body']}"
    )
    return f".github/agents/{role['name']}.agent.md", out


TARGETS = {"claude": render_claude, "opencode": render_opencode, "copilot": render_copilot}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--target", action="append", choices=sorted(TARGETS), help="limit to these targets")
    ap.add_argument("--check", action="store_true", help="fail if generated files differ from roles")
    args = ap.parse_args()

    role_files = sorted(ROLES_DIR.glob("*.md"))
    if not role_files:
        print(f"No roles found in {ROLES_DIR}", file=sys.stderr)
        return 1
    try:
        roles = [parse_role(p) for p in role_files]
    except RoleError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1

    stale = []
    for target in args.target or sorted(TARGETS):
        for role in roles:
            rel, content = TARGETS[target](role)
            path = ROOT / rel
            current = path.read_text(encoding="utf-8") if path.exists() else None
            if current == content:
                continue
            if args.check:
                stale.append(rel)
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
                print(f"wrote {rel}")

    if stale:
        print("Stale agent adapters (run scripts/sync_agents.py):", *stale, sep="\n  ", file=sys.stderr)
        return 1
    if args.check:
        print("Agent adapters are up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
